// ============================================================================
// games/aces/server/src/room.ts — S_ROOM: the ACES room lifecycle integrator.
//
// Owns: the phase machine (lobby -> live -> end -> auto-restart live, same
// seed), seat/bot-fill bookkeeping, the TICK_RATE interval, input intake
// (latest-wins, stale-seq dropped HERE — the World trusts us, see world.ts
// header note), the respawn queue, tickets/scoring, debug verbs, and snapshot
// + event broadcast. The World (S_SIM) knows nothing about phases, tickets,
// sockets or time — every cross-boundary fact flows through the narrow seam
// documented at each call site.
//
// Tick order (FIXED):
//   roomTick -> [lobby: countdown | live: simTick | end: restart dwell]
//            -> pending-score flush -> snapshot cadence (every other tick)
//   simTick  -> match clock -> World.step(dt) -> event flush (+kill
//            bookkeeping / tickets / win) -> respawn queue
//
// Clocks: everything gameplay-coupled counts WORLD/ROOM TICKS, never wall
// time — the debug `tick` verb fast-forwards the sim without moving the wall
// clock, so a mixed clock would desync the respawn queue and match timer
// under e2e fast-forward. Date.now() appears only where wall time IS the
// point: input staleness (STALE_SECONDS) and the 1/s scoreboard rate limit
// (RULES 3 sanctions Date.now for clocks).
//
// Deviation note (reported): CONTRACT §4 S_ROOM says "the room never mints"
// ids/codes, but the FROZEN GameRoomHandle requires `readonly id` populated
// by the room and platform/server/src/lobby.ts keys rooms by room.id and its
// private-create path documents "code generated by the room" — no injection
// path exists. House precedent (outpost/rift) mints both locally; we do the
// same using the RULES 3 identity exception: crypto.randomUUID() only, never
// Math.random.
// ============================================================================
